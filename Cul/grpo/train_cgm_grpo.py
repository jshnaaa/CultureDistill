"""
CGM-GRPO: Culture-Guided Mixed-Policy GRPO

Core innovation over standard GRPO (train_grpo_v3.py):
  - Guardian signal as advantage augmentation (NOT participating in RLOO baseline)
  - Three-factor cultural difficulty coefficient w_culture:
      w_culture = lambda1*(1-hit_rate) + lambda2*rarity_i + lambda3*(1-affinity_i)
  - Guardian quality-gated signal:
      S_guardian = R_outcome^guardian * (R_guardian - R_on_bar)
  - Similarity modulation:
      bonus_i = lambda * w_culture * S_guardian * Sim(y_i, y_guardian)
  - Final advantage: A_i = A_i^base + bonus_i
  - Guardian does NOT participate in policy gradient (no IS needed)

Key differences from train_grpo_v3.py:
  - w_culture is computed dynamically per prompt (not a fixed scalar)
  - Guardian R_guardian uses PRM scoring (alpha*R_outcome + (1-alpha)*Mean(R_process))
  - Two gate mechanisms: quality gate + necessity gate
  - Supports --w_culture_mode: "hit_only" / "hit_rarity" / "full"

Architecture (same as v3):
  - Policy: base model + SFT-LoRA merged + new GRPO-LoRA (trainable) on cuda:0
  - Reference: same model with adapter disabled (zero extra memory)
  - PRM: loaded on cuda:1 for parallel scoring

Hardware requirement: 2x vGPU-48GB

Usage:
    # MVP mode (w_culture = 1 - hit_rate only)
    python Cul/grpo/train_cgm_grpo.py \\
        --model_name     qwen \\
        --sft_adapter    /path/to/camad_sft_qwen/best \\
        --data_pkl       /path/to/normad_splits.pkl \\
        --prm_path       /path/to/camad_prm/best \\
        --guardian_data  /path/to/normad_hf_cac_inference.jsonl \\
        --output_dir     /path/to/models/camad_cgm_grpo_qwen \\
        --w_culture_mode hit_only \\
        --lambda_guide   0.5 \\
        --n_samples      5 \\
        --max_rounds     20 \\
        --eval_every     5

    # Full three-factor mode with affinity matrix
    python Cul/grpo/train_cgm_grpo.py \\
        --model_name     qwen \\
        --sft_adapter    /path/to/camad_sft_qwen/best \\
        --data_pkl       /path/to/normad_splits.pkl \\
        --prm_path       /path/to/camad_prm/best \\
        --guardian_data  /path/to/normad_hf_cac_inference.jsonl \\
        --affinity_config Cul/configs/hf_cac_config.yaml \\
        --output_dir     /path/to/models/camad_cgm_grpo_qwen \\
        --w_culture_mode full \\
        --lambda_guide   0.5 \\
        --alpha          0.6 \\
        --n_samples      5 \\
        --max_rounds     20 \\
        --batches_per_round 130 \\
        --eval_every     5

    The --data_pkl file should be generated by split_data.py (train/val/test splits).
"""

