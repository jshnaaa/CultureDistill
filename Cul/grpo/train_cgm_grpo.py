def train(args):
    if not args.no_prm and args.prm_path is None:
        raise ValueError("--prm_path is required when PRM scoring is enabled.")

    if args.guardian_data is None:
        raise ValueError("--guardian_data is required for CGM-GRPO. "
                         "Use train_grpo_v3.py for standard GRPO.")

    policy_device = torch.device("cuda:0")
    prm_device = torch.device("cuda:1" if torch.cuda.device_count() > 1 else "cuda:0")

    model_path = MODEL_ALIASES.get(args.model_name, args.model_name)

    # ---- Load Guardian index ----
    guardian_index = load_guardian_index(args.guardian_data)

    print(f"{'=' * 60}")
    print(f"CGM-GRPO: Culture-Guided Mixed-Policy GRPO")
    print(f"{'=' * 60}")
    print(f"Base model:      {model_path}")
    print(f"SFT adapter:     {args.sft_adapter or 'None (RL-only)'}")
    print(f"PRM path:        {args.prm_path}")
    print(f"Policy device:   {policy_device}")
    print(f"PRM device:      {prm_device}")
    print(f"Alpha:           {args.alpha}")
    print(f"KL coef:         {KL_COEF}")
    print(f"Lambda guide:    {args.lambda_guide}")
    print(f"w_culture mode:  {args.w_culture_mode}")
    print(f"Sim mode:        {args.guardian_sim_mode}")
    print(f"Necessity gate:  hit_rate >= {args.hit_rate_threshold}")
    print(f"LoRA rank:       {args.lora_r}")
    print(f"Eval every:      {args.eval_every} round(s)")

    # ---- Load data ----
    print(f"Loading data splits from: {args.data_pkl}")
    with open(args.data_pkl, "rb") as f:
        splits = pickle.load(f)
    train_data = splits["train"]
    val_data = splits["val"]
    print(f"  Data: train={len(train_data)}, val={len(val_data)}, "
          f"test={len(splits['test'])}")

    # ---- Initialize w_culture computer ----
    w_culture_computer = CultureDifficultyComputer(
        mode=args.w_culture_mode,
        train_samples=train_data,
        affinity_config_path=args.affinity_config,
    )

    # ---- Tokenizer ----
    tokenizer = AutoTokenizer.from_pretrained(model_path, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "left"

    # ---- Build Policy model ----
    base_model = AutoModelForCausalLM.from_pretrained(
        model_path, torch_dtype=torch.bfloat16, trust_remote_code=True
    )

    if args.sft_adapter:
        print(f"  Merging SFT LoRA adapter: {args.sft_adapter}")
        base_model = PeftModel.from_pretrained(base_model, args.sft_adapter)
        base_model = base_model.merge_and_unload()
        print(f"  SFT adapter merged into base model")

    lora_config = LoraConfig(
        task_type=TaskType.CAUSAL_LM,
        r=args.lora_r,
        lora_alpha=args.lora_alpha,
        lora_dropout=0.05,
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj",
                        "gate_proj", "up_proj", "down_proj"],
        bias="none",
    )
    policy = get_peft_model(base_model, lora_config).to(policy_device)
    policy.print_trainable_parameters()
    policy.enable_input_require_grads()
    policy.gradient_checkpointing_enable()

    # ---- PRM (frozen, on second GPU) ----
    if not args.no_prm:
        prm_backbone = args.prm_backbone if args.prm_backbone else model_path
        prm = CulturePRM_v3(
            prm_checkpoint_dir=args.prm_path,
            backbone_path=prm_backbone,
            sft_adapter_path=args.sft_adapter,
        ).to(prm_device)
        prm_tokenizer = AutoTokenizer.from_pretrained(
            prm_backbone, trust_remote_code=True
        )
        if prm_tokenizer.pad_token is None:
            prm_tokenizer.pad_token = prm_tokenizer.eos_token
        for p in prm.parameters():
            p.requires_grad_(False)
        prm.eval()
    else:
        prm = None
        prm_tokenizer = None
        print("  [PRM] Skipped (--no_prm mode)")

    # ---- Optimizer ----
    trainable_params = [p for p in policy.parameters() if p.requires_grad]
    optimizer = torch.optim.AdamW(
        trainable_params, lr=args.lr, weight_decay=0.0, betas=(0.9, 0.95)
    )

    # ---- Dataset ----
    grpo_ds = GRPOPromptDataset(train_data)
    loader = DataLoader(grpo_ds, batch_size=args.prompt_batch,
                        shuffle=True, pin_memory=False)

    Path(args.output_dir).mkdir(parents=True, exist_ok=True)
    best_val_acc = 0.0
    no_improve = 0

    effective_batches_info = (
        f"all {len(loader)}" if args.batches_per_round < 0
        else f"{min(args.batches_per_round, len(loader))}/{len(loader)}"
    )
    print(f"CGM-GRPO prompts: {len(grpo_ds)} | "
          f"Rounds: {args.max_rounds} | n_samples: {args.n_samples}")
    print(f"Batches per round: {effective_batches_info}")
    print(f"PRM scoring: {'DISABLED' if args.no_prm else 'ENABLED'}")
    print(f"Starting training...")
    sys.stdout.flush()

    # ---- Training rounds ----
    for rnd in range(1, args.max_rounds + 1):
        round_loss = 0.0
        round_steps = 0
        round_r_outcome = 0.0
        round_r_process = 0.0
        round_r_total = 0.0
        round_cgm_bonus = 0.0
        round_w_culture = 0.0
        round_s_guardian = 0.0
        round_guardian_found = 0
        round_guardian_correct = 0
        round_n = 0
        round_cgm_batches = 0

        effective_batches = (len(loader) if args.batches_per_round < 0
                            else min(args.batches_per_round, len(loader)))

        for batch_idx, batch in enumerate(loader):
            if batch_idx >= effective_batches:
                break

            queries = batch["query"]
            countries = batch["country"]
            golds = batch["gt"]
            n_prompts = len(queries)

            if batch_idx % 5 == 0:
                print(f"  Round {rnd} | Batch {batch_idx+1}/{effective_batches} | "
                      f"Gen {n_prompts}x{args.n_samples}...", flush=True)

            # 1. Build prompts
            prompts = [build_prompt(q, c, tokenizer)
                       for q, c in zip(queries, countries)]

            # 2. Generate on-policy responses
            policy.eval()
            policy.gradient_checkpointing_disable()
            all_responses = generate_responses(
                policy, tokenizer, prompts,
                n_samples=args.n_samples,
                max_new_tokens=MAX_GEN_LEN,
                temperature=args.temperature,
                device=policy_device,
            )
            policy.gradient_checkpointing_enable()
            policy.train()
            torch.cuda.empty_cache()

            # 3. Compute rewards
            rewards = torch.zeros(n_prompts, args.n_samples, device=policy_device)
            r_outcomes = []

            for pi, (responses, gold) in enumerate(zip(all_responses, golds)):
                for si, resp in enumerate(responses):
                    pred = extract_answer(resp)
                    r_outcomes.append(compute_r_outcome(pred, str(gold).strip()))

            if args.no_prm:
                r_processes = [0.0] * (n_prompts * args.n_samples)
            else:
                prm_inputs = []
                for pi, (responses, query, country) in enumerate(
                    zip(all_responses, queries, countries)
                ):
                    for si, resp in enumerate(responses):
                        prm_inputs.append(build_prm_input(country, query, resp))

                PRM_BATCH_SIZE = 20
                r_processes = []
                for i in range(0, len(prm_inputs), PRM_BATCH_SIZE):
                    batch_texts = prm_inputs[i:i + PRM_BATCH_SIZE]
                    batch_scores = prm.score_batch(
                        batch_texts, prm_tokenizer, prm_device, max_len=512
                    )
                    r_processes.extend(batch_scores)

            idx = 0
            for pi in range(n_prompts):
                for si in range(args.n_samples):
                    r_outcome = r_outcomes[idx]
                    r_process = r_processes[idx]
                    if args.no_prm:
                        r_total = r_outcome
                    else:
                        r_total = (args.alpha * r_outcome +
                                   (1 - args.alpha) * r_process)
                    rewards[pi, si] = r_total
                    round_r_outcome += r_outcome
                    round_r_process += r_process
                    round_r_total += r_total
                    round_n += 1
                    idx += 1

            # 4. RLOO advantages (base)
            advantages = rloo_advantages(rewards)

            # 4b. CGM-GRPO advantage bonus
            cgm_bonus, cgm_stats = compute_cgm_advantage_bonus(
                queries=queries,
                countries=countries,
                golds=golds,
                all_responses=all_responses,
                r_outcomes_flat=r_outcomes,
                guardian_index=guardian_index,
                lambda_guide=args.lambda_guide,
                w_culture_computer=w_culture_computer,
                sim_mode=args.guardian_sim_mode,
                n_samples=args.n_samples,
                prm=prm,
                prm_tokenizer=prm_tokenizer,
                prm_device=prm_device,
                alpha=args.alpha,
                device=policy_device,
                hit_rate_threshold=args.hit_rate_threshold,
            )
            advantages = advantages + cgm_bonus
            round_cgm_bonus += cgm_bonus.abs().mean().item()
            round_w_culture += cgm_stats["mean_w_culture"]
            round_s_guardian += cgm_stats["mean_s_guardian"]
            round_guardian_found += cgm_stats["guardian_found"]
            round_guardian_correct += cgm_stats["guardian_correct"]
            round_cgm_batches += 1

            # 5. Policy gradient with KL penalty
            total_samples = n_prompts * args.n_samples

            # Phase A: Reference log-probs
            policy.eval()
            policy.gradient_checkpointing_disable()
            ref_logprobs = {}
            with torch.no_grad():
                with policy.disable_adapter():
                    for pi, (prompt, responses) in enumerate(
                        zip(prompts, all_responses)
                    ):
                        for si, resp in enumerate(responses):
                            adv = advantages[pi, si].item()
                            if abs(adv) < 1e-8:
                                continue
                            lp_ref = compute_logprobs(
                                policy, tokenizer, prompt, resp,
                                policy_device, require_grad=False,
                            )
                            ref_logprobs[(pi, si)] = lp_ref.item()

            # Phase B: Policy forward+backward
            policy.gradient_checkpointing_enable()
            policy.train()
            optimizer.zero_grad()
            loss_count = 0
            accumulated_loss = 0.0

            for pi, (prompt, responses) in enumerate(zip(prompts, all_responses)):
                for si, resp in enumerate(responses):
                    if (pi, si) not in ref_logprobs:
                        continue

                    adv = advantages[pi, si].item()
                    lp_ref_val = ref_logprobs[(pi, si)]

                    lp_policy = compute_logprobs(
                        policy, tokenizer, prompt, resp,
                        policy_device, require_grad=True,
                    )

                    lp_ref_t = torch.tensor(lp_ref_val, device=policy_device)
                    kl = (lp_policy - lp_ref_t).clamp(min=-10, max=10)
                    pg_loss = -(adv * lp_policy - KL_COEF * kl) / total_samples

                    pg_loss.backward()
                    accumulated_loss += pg_loss.item()
                    loss_count += 1

                    if loss_count % 10 == 0:
                        print(f"    PG step {loss_count}/{len(ref_logprobs)}",
                              flush=True)

            if loss_count > 0:
                torch.nn.utils.clip_grad_norm_(trainable_params, 1.0)
                optimizer.step()
                round_loss += accumulated_loss
                round_steps += 1

        # Round summary
        avg_loss = round_loss / max(round_steps, 1)
        avg_r_outcome = round_r_outcome / max(round_n, 1)
        avg_r_process = round_r_process / max(round_n, 1)
        avg_r_total = round_r_total / max(round_n, 1)
        avg_cgm = round_cgm_bonus / max(round_cgm_batches, 1)
        avg_wc = round_w_culture / max(round_cgm_batches, 1)
        avg_sg = round_s_guardian / max(round_cgm_batches, 1)

        print(f"Round {rnd}/{args.max_rounds} | "
              f"loss={avg_loss:.4f} | "
              f"R_out={avg_r_outcome:.3f} | "
              f"R_proc={avg_r_process:.3f} | "
              f"R_total={avg_r_total:.3f}")
        print(f"  CGM: bonus={avg_cgm:.4f} | "
              f"w_culture={avg_wc:.3f} | "
              f"S_guard={avg_sg:.3f} | "
              f"G_found={round_guardian_found} | "
              f"G_correct={round_guardian_correct}")

        # 6. Validation
        if rnd % args.eval_every == 0:
            val_acc = validate(policy, tokenizer, val_data, policy_device)
            print(f"  [Eval] Round {rnd} | val_accuracy={val_acc:.4f}")

            if val_acc > best_val_acc:
                best_val_acc = val_acc
                no_improve = 0
                ckpt = Path(args.output_dir) / "best"
                policy.save_pretrained(str(ckpt))
                tokenizer.save_pretrained(str(ckpt))
                print(f"  Saved best CGM-GRPO LoRA "
                      f"(val_acc={best_val_acc:.4f}) -> {ckpt}")
            else:
                no_improve += 1
                print(f"  No improvement ({no_improve}/3)")
                if no_improve >= 3:
                    print("Early stopping.")
                    break

    if best_val_acc == 0.0:
        ckpt = Path(args.output_dir) / "best"
        policy.save_pretrained(str(ckpt))
        tokenizer.save_pretrained(str(ckpt))
        print(f"  Saved final CGM-GRPO LoRA -> {ckpt}")

    print(f"\nTraining complete. Best val_accuracy: {best_val_acc:.4f}")
    print(f"Best CGM-GRPO LoRA adapter: {args.output_dir}/best")


