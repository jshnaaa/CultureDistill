def get_culture_circle(country: str) -> int:
    """Map a country string to its culture circle index (0-5). Returns -1 if unknown."""
    country_lower = country.lower().strip()
    if country_lower in COUNTRY_TO_CIRCLE:
        return COUNTRY_TO_CIRCLE[country_lower]
    for kw, cid in COUNTRY_TO_CIRCLE.items():
        if kw in country_lower or country_lower in kw:
            return cid
    return -1


# ---------------------------------------------------------------------------
# Cultural Difficulty Coefficient: w_culture
# ---------------------------------------------------------------------------

class CultureDifficultyComputer:
    """
    Computes the three-factor cultural difficulty coefficient w_culture.

    Modes:
      - "hit_only": w = 1 - hit_rate (MVP)
      - "hit_rarity": w = 0.67*(1-hit_rate) + 0.33*rarity_i
      - "full": w = 0.6*(1-hit_rate) + 0.3*rarity_i + 0.1*(1-affinity_i)
    """

    def __init__(self, mode: str, train_samples: list, affinity_config_path: str = None):
        self.mode = mode
        self.rarity_map = {}
        self.affinity_map = {}

        if mode in ("hit_rarity", "full"):
            self._compute_rarity(train_samples)

        if mode == "full":
            if affinity_config_path is None:
                raise ValueError("--affinity_config required for w_culture_mode='full'")
            self._load_affinity(affinity_config_path)

    def _compute_rarity(self, train_samples: list):
        """Compute rarity_i = 1 - freq_i for each culture circle."""
        circle_counts = defaultdict(int)
        total = 0
        for sample in train_samples:
            country = sample.get("country", "")
            circle = get_culture_circle(country)
            if circle >= 0:
                circle_counts[circle] += 1
                total += 1

        if total == 0:
            for i in range(6):
                self.rarity_map[i] = 0.5
            return

        for i in range(6):
            freq = circle_counts[i] / total
            self.rarity_map[i] = 1.0 - freq

        print(f"  [w_culture] Rarity stats (total={total}):")
        circle_names = ["Western", "Latin American", "Sub-Saharan African",
                        "East-Asian", "Islamic & Middle-Eastern", "South & SE Asian"]
        for i in range(6):
            freq = circle_counts[i] / total
            print(f"    {circle_names[i]}: count={circle_counts[i]}, "
                  f"freq={freq:.3f}, rarity={self.rarity_map[i]:.3f}")

    def _load_affinity(self, config_path: str):
        """Load affinity matrix and compute mean non-diagonal affinity per circle."""
        with open(config_path, "r", encoding="utf-8") as f:
            cfg = yaml.safe_load(f)

        matrix = cfg["cultural_affinity_matrix"]
        for i in range(6):
            row = matrix[i]
            non_diag = [row[j] for j in range(6) if j != i]
            self.affinity_map[i] = sum(non_diag) / len(non_diag)

        print(f"  [w_culture] Affinity map loaded from {config_path}")
        circle_names = ["Western", "Latin American", "Sub-Saharan African",
                        "East-Asian", "Islamic & Middle-Eastern", "South & SE Asian"]
        for i in range(6):
            print(f"    {circle_names[i]}: mean_affinity={self.affinity_map[i]:.3f}, "
                  f"(1-affinity)={1-self.affinity_map[i]:.3f}")

    def compute(self, hit_rate: float, country: str) -> float:
        """Compute w_culture for a given prompt."""
        if self.mode == "hit_only":
            return 1.0 - hit_rate

        circle = get_culture_circle(country)

        if self.mode == "hit_rarity":
            rarity = self.rarity_map.get(circle, 0.5)
            return 0.67 * (1.0 - hit_rate) + 0.33 * rarity

        # full mode
        rarity = self.rarity_map.get(circle, 0.5)
        affinity = self.affinity_map.get(circle, 0.3)
        return (W_CULTURE_LAMBDA1 * (1.0 - hit_rate) +
                W_CULTURE_LAMBDA2 * rarity +
                W_CULTURE_LAMBDA3 * (1.0 - affinity))


# ---------------------------------------------------------------------------
# CGM-GRPO: Guardian Advantage with PRM Scoring
# ---------------------------------------------------------------------------

def compute_guardian_r_total(
    guardian_text: str,
    guardian_answer: str,
    gold: str,
    country: str,
    query: str,
    prm,
    prm_tokenizer,
    prm_device,
    alpha: float,
):
    """
    Compute R_guardian = alpha * R_outcome_guardian + (1-alpha) * Mean(R_process_guardian).
    Returns (r_guardian, r_outcome_guardian).
    """
    r_outcome_guardian = compute_r_outcome(guardian_answer, gold)

    if prm is None:
        return r_outcome_guardian, r_outcome_guardian

    prm_input = build_prm_input(country, query, guardian_text)
    r_process_guardian = prm.score_reasoning(prm_input, prm_tokenizer, prm_device)

    r_guardian = alpha * r_outcome_guardian + (1.0 - alpha) * r_process_guardian
    return r_guardian, r_outcome_guardian


def compute_cgm_advantage_bonus(
    queries, countries, golds, all_responses, r_outcomes_flat,
    guardian_index, lambda_guide, w_culture_computer, sim_mode,
    n_samples, prm, prm_tokenizer, prm_device, alpha, device,
    hit_rate_threshold=0.8,
):
    """
    Compute the CGM-GRPO advantage bonus for a batch.

    Formula: bonus[pi, si] = lambda * w_culture * S_guardian * Sim(y_i, y_guardian)
    Gates: quality gate (Guardian correct) + necessity gate (hit_rate < threshold)

    Returns (bonus_tensor, stats_dict).
    """
    n_prompts = len(queries)
    bonus = torch.zeros(n_prompts, n_samples, device=device)

    stats = {
        "guardian_found": 0,
        "guardian_correct": 0,
        "guardian_skipped_quality": 0,
        "guardian_skipped_necessity": 0,
        "mean_w_culture": 0.0,
        "mean_s_guardian": 0.0,
    }

    w_culture_sum = 0.0
    s_guardian_sum = 0.0
    active_count = 0

    for pi in range(n_prompts):
        country = countries[pi]
        query = queries[pi]
        gold = str(golds[pi]).strip()

        key = (country.lower().strip(), query[:200].lower().strip())
        guardian_data = guardian_index.get(key, None)

        if guardian_data is None:
            continue

        stats["guardian_found"] += 1
        guardian_answer = guardian_data["guardian_answer"]
        guardian_response = guardian_data["guardian_response"]

        if guardian_answer is None:
            continue

        # Compute hit_rate for this prompt
        start_idx = pi * n_samples
        prompt_r_outcomes = r_outcomes_flat[start_idx:start_idx + n_samples]
        hit_rate = sum(1.0 for r in prompt_r_outcomes if r > 0.5) / max(n_samples, 1)

        # Necessity gate
        if hit_rate >= hit_rate_threshold:
            stats["guardian_skipped_necessity"] += 1
            continue

        # Compute R_guardian (with PRM scoring)
        r_guardian, r_outcome_guardian = compute_guardian_r_total(
            guardian_text=guardian_response,
            guardian_answer=guardian_answer,
            gold=gold,
            country=country,
            query=query,
            prm=prm,
            prm_tokenizer=prm_tokenizer,
            prm_device=prm_device,
            alpha=alpha,
        )

        # Quality gate
        if r_outcome_guardian < 0.5:
            stats["guardian_skipped_quality"] += 1
            continue

        stats["guardian_correct"] += 1

        # R_on_bar_full (full group mean)
        mean_r_on = sum(prompt_r_outcomes) / max(len(prompt_r_outcomes), 1)

        # S_guardian = R_outcome^guardian * (R_guardian - R_on_bar_full)
        s_guardian = r_outcome_guardian * (r_guardian - mean_r_on)

        # w_culture
        w_culture = w_culture_computer.compute(hit_rate, country)

        w_culture_sum += w_culture
        s_guardian_sum += abs(s_guardian)
        active_count += 1

        if abs(s_guardian) < 1e-8:
            continue

        # Similarity modulation per rollout
        for si, resp in enumerate(all_responses[pi]):
            sim = compute_guardian_similarity(resp, guardian_data, sim_mode)
            bonus[pi, si] = lambda_guide * w_culture * s_guardian * sim

    if active_count > 0:
        stats["mean_w_culture"] = w_culture_sum / active_count
        stats["mean_s_guardian"] = s_guardian_sum / active_count

    return bonus, stats


