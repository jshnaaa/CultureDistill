def build_prompt(query: str, country: str, tokenizer) -> str:
    """Build culture-conditioned prompt."""
    content = f"[{country}]\n{query}\n\nReasoning: "
    messages = [{"role": "user", "content": content}]
    return tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )


def build_judge_sft_target(judge_answer: str, judge_text: str) -> str:
    """
    Build the SFT distillation target from the Judge's final decision.

    Uses the Judge's final answer: answer-first digit plus a short rationale
    line (if present in judge_text). Falls back to "Answer: <digit>".
    """
    if judge_answer is None:
        return None
    # Take a short rationale: first non-empty line of judge_text that isn't
    # just the digit/tag, to keep the supervision focused on the final answer.
    rationale = ""
    for line in judge_text.split("\n"):
        s = line.strip()
        if not s:
            continue
        if re.fullmatch(r'[1-4]', s):
            continue
        if s.startswith("["):
            continue
        rationale = s
        break
    if rationale:
        return f"Answer: {judge_answer}\nReason: {rationale}"
    return f"Answer: {judge_answer}"


def extract_answer(text: str):
    """Extract answer from generated response."""
    m = re.search(r"Answer\s*:\s*([1-4])", text, re.IGNORECASE)
    if m:
        return m.group(1)
    m = re.search(r"answer\s+is\s*:?\s*([1-4])\b", text, re.IGNORECASE)
    if m:
        return m.group(1)
    digits = re.findall(r"\b([1-4])\b", text)
    return digits[-1] if digits else None


def compute_r_outcome(predicted, gold: str) -> float:
    """Binary outcome reward."""
    return 1.0 if predicted == gold else 0.0


def build_prm_input(country: str, query: str, reasoning: str) -> str:
    """Build PRM input text with step markers."""
    steps = split_reasoning_into_steps(reasoning)
    if not steps:
        steps = [f"[Step 1] {reasoning}"]
    step_text = "\n".join(steps)
    return f"[{country}]\n{query}\n{step_text}"


def grpo_advantages(rewards: torch.Tensor) -> torch.Tensor:
    """
    Standard GRPO advantage: A_i^base = R_i - mean(R) within each prompt group.
    rewards: (n_prompts, n_samples), returns same shape.
    """
    baseline = rewards.mean(dim=1, keepdim=True)
    return rewards - baseline


