"""
CAMAD: Culture-Aware Adaptive Mixed Distillation (joint SFT+RL).

Core method (see camad.md §6.2):
  - Trains DIRECTLY FROM THE BASE MODEL (no separate SFT warm-up stage). The
    supervised signal is injected ONLINE via the joint loss below. This is the
    key difference from classic RLHF (base -> SFT -> RL): by mixing SFT and RL
    in one optimization step from the base, CAMAD avoids the catastrophic
    forgetting that the staged SFT->RL pipeline suffers from.
  - Joint objective in ONE optimization step:
        L = L_GRPO(A_i) + beta * w_sft * L_SFT
  - RL part (exploration + cultural guidance):
        A_i = A_i^base + lambda_g * w * S_guardian          (per-rollout)
    where A_i^base = R_i - mean(R) is the standard GRPO/RLOO advantage,
    S_guardian in {0,1} indicates whether the rollout's CULTURAL REASONING
    DIRECTION matches the Guardian's judgment (per-rollout).
  - SFT part (Judge distillation, anti-forgetting):
        L_SFT = -log P(y_judge | x),  weighted by w_sft.
    y_judge = HF-CAC Judge final answer (the multi-agent decision).
  - Difficulty-adaptive weights (shared per-prompt hitrate, tracked by EMA):
        w     = 1 - hitrate                         (RL guidance weight, ->0)
        w_sft = max(1 - hitrate, w_min)             (SFT weight, with floor)

Note on Guardian signal semantics:
  HF-CAC inference JSONL stores Guardian/Judge as parsed answer DIGITS only
  (no separate "cultural direction" field). We therefore use the Guardian's
  answer choice as the proxy for cultural direction: S_guardian = 1 iff the
  rollout's parsed choice equals the Guardian's choice. When richer cultural
  direction labels become available in the data, plug them into
  `guardian_cultural_match()` without changing the training loop.

Performance optimizations (inherited):
  - Batch Generate: all prompts in one model.generate() call.
  - Batch LogProb: vectorized forward pass for ref/policy log-probs.
  - Mini-batch backward: accumulate gradients over small groups.

Architecture (LoRA, no DeepSpeed):
  - Policy: BASE model + new trainable LoRA on cuda:0 (joint SFT+RL trained;
    NO pre-merged SFT adapter)
  - Reference: same model with adapter disabled (zero extra memory)
  - PRM: loaded on cuda:1 for parallel scoring (frozen, eval mode)

Hardware requirement: 2x vGPU-48GB (policy on cuda:0, PRM on cuda:1)

Usage:
    # Quick test with 10 samples (trains from BASE; no SFT adapter)
    python Cul/grpo/train_grpo_mixed_policy.py \\
        --model_name     qwen \\
        --data_pkl       /path/to/normad_splits.pkl \\
        --prm_path       /path/to/camad_prm/best \\
        --guardian_data  /path/to/normad_hf_cac_inference.jsonl \\
        --output_dir     /path/to/models/camad \\
        --max_samples    10 \\
        --max_rounds     3 \\
        --n_samples      5

    # Full CAMAD joint SFT+RL training (from BASE model)
    python Cul/grpo/train_grpo_mixed_policy.py \\
        --model_name     qwen \\
        --data_pkl       /path/to/normad_splits.pkl \\
        --prm_path       /path/to/camad_prm/best \\
        --guardian_data  /path/to/normad_hf_cac_inference.jsonl \\
        --output_dir     /path/to/models/camad \\
        --beta           0.3 \\
        --lambda_g       0.5 \\
        --w_min          0.1 \\
        --n_samples      5 \\
        --max_rounds     20 \\
        --batches_per_round 130

    The --data_pkl file should be generated by split_data.py.
    The --guardian_data is the HF-CAC inference JSONL from Stage 0
    (provides both Guardian signal and Judge SFT target).
"""

