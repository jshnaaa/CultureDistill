# Optimized Batch Log-Prob Computation (Optimization 2)
# ---------------------------------------------------------------------------

def batch_compute_logprobs(
    model, tokenizer, prompts: list, responses: list,
    device, require_grad: bool = False,
    mini_batch_size: int = 8,
) -> torch.Tensor:
    """
    Compute the sum of per-token log-probs of `responses` given `prompts`.

    prompts[i] corresponds to responses[i] (flat 1:1 lists).

    Returns:
        Tensor of shape (N,) with summed log-prob of each response.
        If require_grad=True, the returned tensor is part of the autograd graph.
    """
    assert len(prompts) == len(responses)
    n = len(prompts)
    out = [] if require_grad else torch.zeros(n, device=device)

    ctx = torch.enable_grad() if require_grad else torch.no_grad()
    with ctx:
        for start in range(0, n, mini_batch_size):
            b_prompts = prompts[start:start + mini_batch_size]
            b_resps = responses[start:start + mini_batch_size]

            full_texts = [p + r for p, r in zip(b_prompts, b_resps)]
            enc = tokenizer(
                full_texts, return_tensors="pt", padding=True,
                max_length=MAX_PROMPT_LEN + MAX_GEN_LEN, truncation=True,
            ).to(device)

            # Lengths of prompt-only parts (to mask out prompt tokens).
            prompt_enc = tokenizer(
                b_prompts, padding=False, truncation=True,
                max_length=MAX_PROMPT_LEN,
            )
            prompt_lens = [len(ids) for ids in prompt_enc["input_ids"]]

            logits = model(
                input_ids=enc["input_ids"],
                attention_mask=enc["attention_mask"],
            ).logits  # (B, T, V)

            log_probs = torch.log_softmax(logits[:, :-1, :], dim=-1)
            target_ids = enc["input_ids"][:, 1:]
            token_lp = log_probs.gather(
                2, target_ids.unsqueeze(-1)
            ).squeeze(-1)  # (B, T-1)

            attn = enc["attention_mask"][:, 1:]
            for bi in range(len(b_prompts)):
                p_len = prompt_lens[bi]
                # Response tokens start at index p_len in the full sequence;
                # in the shifted (T-1) space they start at p_len - 1.
                resp_start = max(0, p_len - 1)
                mask = attn[bi].clone().float()
                mask[:resp_start] = 0.0
                lp_sum = (token_lp[bi] * mask).sum()
                if require_grad:
                    out.append(lp_sum)
                else:
                    out[start + bi] = lp_sum.detach()

    if require_grad:
        return torch.stack(out)
    return out


def compute_sft_loss(
    model, tokenizer, prompts: list, targets: list, device,
    mini_batch_size: int = 4,
) -> torch.Tensor:
    """
    Supervised distillation loss L_SFT = mean(-log P(y_judge | x)) over the
    response tokens, returned WITH grad.

    prompts[i] pairs with targets[i] (Judge final-answer text). Entries with a
    None target are skipped. Returns a scalar tensor (0.0 if nothing to train).
    """
    pairs = [(p, t) for p, t in zip(prompts, targets) if t is not None]
    if not pairs:
        return torch.zeros((), device=device)

    total_nll = torch.zeros((), device=device)
    total_tokens = 0

    for start in range(0, len(pairs), mini_batch_size):
        batch = pairs[start:start + mini_batch_size]
        b_prompts = [p for p, _ in batch]
        b_targets = [t for _, t in batch]

        full_texts = [p + t for p, t in zip(b_prompts, b_targets)]
        enc = tokenizer(
            full_texts, return_tensors="pt", padding=True,
            max_length=MAX_PROMPT_LEN + MAX_GEN_LEN, truncation=True,
        ).to(device)

        prompt_enc = tokenizer(
            b_prompts, padding=False, truncation=True,
            max_length=MAX_PROMPT_LEN,
        )
        prompt_lens = [len(ids) for ids in prompt_enc["input_ids"]]

        logits = model(
            input_ids=enc["input_ids"],
            attention_mask=enc["attention_mask"],
        ).logits
        log_probs = torch.log_softmax(logits[:, :-1, :], dim=-1)
        target_ids = enc["input_ids"][:, 1:]
        token_lp = log_probs.gather(
            2, target_ids.unsqueeze(-1)
        ).squeeze(-1)
        attn = enc["attention_mask"][:, 1:]

        for bi in range(len(batch)):
            resp_start = max(0, prompt_lens[bi] - 1)
            mask = attn[bi].clone().float()
            mask[:resp_start] = 0.0
            n_tok = mask.sum()
            if n_tok.item() == 0:
                continue
            total_nll = total_nll + (-(token_lp[bi] * mask).sum())
            total_tokens += int(n_tok.item())

    if total_tokens == 0:
        return torch.zeros((), device=device)
    return total_nll / total_tokens


