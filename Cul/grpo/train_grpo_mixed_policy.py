# Difficulty-adaptive weights: per-prompt hitrate tracked by EMA
# ---------------------------------------------------------------------------

class HitRateTracker:
    """
    Track per-prompt hitrate (cultural mastery) with optional EMA smoothing,
    and derive the RL guidance weight w and the SFT weight w_sft.

        w     = 1 - hitrate                       (can decay to 0)
        w_sft = max(1 - hitrate, w_min)           (floored, anti-forgetting)

    hitrate update:
        EMA on:  hitrate <- m * prev + (1 - m) * acc_cur
        EMA off: hitrate <- acc_cur                (current-round value)
    """

    def __init__(self, w_min: float = 0.1, momentum: float = 0.9,
                 use_ema: bool = True):
        self.w_min = w_min
        self.momentum = momentum
        self.use_ema = use_ema
        self._hitrate = {}  # prompt_key -> float

    @staticmethod
    def _key(country: str, query: str) -> tuple:
        return (country.lower().strip(), query[:200].lower().strip())

    def update(self, country: str, query: str, acc_cur: float) -> float:
        """Update and return the smoothed hitrate for a prompt."""
        key = self._key(country, query)
        if self.use_ema and key in self._hitrate:
            prev = self._hitrate[key]
            hr = self.momentum * prev + (1.0 - self.momentum) * acc_cur
        else:
            hr = acc_cur
        self._hitrate[key] = hr
        return hr

    def weights(self, hitrate: float) -> tuple:
        """Return (w, w_sft) given a hitrate."""
        w = max(0.0, 1.0 - hitrate)
        w_sft = max(w, self.w_min)
        return w, w_sft


def guardian_cultural_match(rollout_pred: str, guardian_answer: str) -> int:
    """
    Per-rollout cultural-direction signal S_guardian in {0, 1}.

    Defined as whether the rollout's cultural reasoning DIRECTION matches the
    Guardian's judgment. With the current HF-CAC data (answer digits only), we
    use the Guardian's answer choice as the cultural-direction proxy:
        S_guardian = 1 iff rollout_pred == guardian_answer.

    If a future data format provides an explicit cultural-direction label for
    each rollout, replace this comparison accordingly (the training loop is
    agnostic to how this 0/1 is computed).
    """
    if guardian_answer is None or rollout_pred is None:
        return 0
    return 1 if str(rollout_pred).strip() == str(guardian_answer).strip() else 0


