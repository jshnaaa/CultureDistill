@torch.no_grad()
def batch_generate_responses(
    model, tokenizer, prompts: list, n_samples: int,
    max_new_tokens: int, temperature: float, device,
    mini_batch_size: int = 4,
) -> list:
    """
    Generate n_samples responses per prompt using BATCHED generation.

    Returns:
        all_responses[prompt_idx] = [resp_0, ..., resp_{n_samples-1}]
    """
    all_responses = [[] for _ in range(len(prompts))]

    for start in range(0, len(prompts), mini_batch_size):
        batch_prompts = prompts[start:start + mini_batch_size]
        batch_size = len(batch_prompts)

        enc = tokenizer(
            batch_prompts,
            return_tensors="pt",
            padding=True,
            max_length=MAX_PROMPT_LEN,
            truncation=True,
        ).to(device)

        outs = model.generate(
            **enc,
            max_new_tokens=max_new_tokens,
            do_sample=True,
            temperature=temperature,
            num_return_sequences=n_samples,
            pad_token_id=tokenizer.pad_token_id,
        )

        prompt_lens = enc["attention_mask"].sum(dim=1)

        for bi in range(batch_size):
            prompt_len = prompt_lens[bi].item()
            for si in range(n_samples):
                out_idx = bi * n_samples + si
                response_ids = outs[out_idx][prompt_len:]
                response = tokenizer.decode(response_ids, skip_special_tokens=True)
                all_responses[start + bi].append(response)

    return all_responses


