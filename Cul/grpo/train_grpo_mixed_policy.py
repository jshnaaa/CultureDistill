def load_hf_cac_index(jsonl_path: str) -> dict:
    """
    Load HF-CAC inference JSONL and build a lookup index keyed by
    (country_lower, query_prefix_lower).

    Each value carries both:
      - guardian_answer : Guardian's parsed choice digit (cultural direction proxy)
      - judge_answer    : Judge's final decision digit  (SFT distillation target)
      - judge_text      : Judge's final answer text (for richer SFT target)

    Returns:
        dict[(country, query_prefix)] -> {
            "guardian_answer": str | None,
            "judge_answer": str | None,
            "judge_text": str,
        }
    """
    index = {}
    n_guardian = 0
    n_judge = 0
    with open(jsonl_path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            obj = json.loads(line)
            query = obj.get("query", "").strip()
            country = obj.get("country", "").strip()
            response = obj.get("response", "")

            guardian_text = _extract_guardian_text(response)
            guardian_answer = (_extract_answer_digit(guardian_text)
                               if guardian_text else None)
            judge_text = _extract_judge_text(response)
            judge_answer = (_extract_answer_digit(judge_text)
                            if judge_text else None)

            if guardian_answer is not None:
                n_guardian += 1
            if judge_answer is not None:
                n_judge += 1

            key = (country.lower(), query[:200].lower())
            index[key] = {
                "guardian_answer": guardian_answer,
                "judge_answer": judge_answer,
                "judge_text": judge_text,
            }

    print(f"  [HF-CAC] Loaded {len(index)} records from {jsonl_path} "
          f"(guardian={n_guardian}, judge={n_judge})")
    return index


def _extract_guardian_text(formatted_response: str) -> str:
    """Extract Guardian's text block from formatted multi-agent response."""
    pattern = r'===== Solution \d+ \[GUARDIAN\] =====\n(.*?)(?=\n===== Solution|\Z)'
    match = re.search(pattern, formatted_response, re.DOTALL)
    if match:
        return match.group(1).strip()
    return ""


def _extract_judge_text(formatted_response: str) -> str:
    """Extract Judge's text block (handles all judge mode tags)."""
    pattern = r'===== Solution \d+ \[JUDGE[^\]]*\] =====\n(.*?)(?=\n===== Solution|\Z)'
    match = re.search(pattern, formatted_response, re.DOTALL)
    if match:
        return match.group(1).strip()
    return ""


def _extract_answer_digit(text: str) -> str:
    """Extract an answer digit (1-4) from an agent text block."""
    if not text:
        return None
    first_line = text.split("\n")[0].strip()
    m = re.match(r'^([1-4])\b', first_line)
    if m:
        return m.group(1)
    m = re.search(r"Answer\s*:\s*([1-4])", text, re.IGNORECASE)
    if m:
        return m.group(1)
    digits = re.findall(r"\b([1-4])\b", text)
    return digits[0] if digits else None


def lookup_hf_cac(index: dict, country: str, query: str) -> dict:
    """Look up an HF-CAC record by (country, query prefix)."""
    if not index:
        return None
    key = (country.lower().strip(), query[:200].lower().strip())
    return index.get(key, None)


