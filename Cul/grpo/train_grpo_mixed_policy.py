@torch.no_grad()
def batch_generate_responses(
    model, tokenizer, prompts: list, n_samples: int,
    max_new_tokens: int, temperature: float, device,
    mini_batch_size: int = 4,
) -> list:
    """
    Generate n_samples responses per prompt using BATCHED generation.

    Instead of generating one prompt at a time (serial), we batch multiple
    prompts together for much higher GPU utilization.

    Memory control: mini_batch_size prompts * n_samples sequences at once.
    With mini_batch_size=4, n_samples=5: 20 sequences simultaneously.
    Peak KV cache: ~20 * 640 tokens * 4096 hidden * 2 (K+V) * 28 layers * 2B
                 = ~4.5 GB (bf16). Fits comfortably in 48GB.

    Args:
        mini_batch_size: Prompts per generation call (default: 4).
            Reduce to 2 if OOM during generation.

    Returns:
        all_responses[prompt_idx] = [resp_0, ..., resp_{n_samples-1}]
    """
    all_responses = [[] for _ in range(len(prompts))]

    for start in range(0, len(prompts), mini_batch_size):
        batch_prompts = prompts[start:start + mini_batch_size]
        batch_size = len(batch_prompts)

        # Left-pad tokenization for batch generation
        enc = tokenizer(
            batch_prompts,
            return_tensors="pt",
            padding=True,
            max_length=MAX_PROMPT_LEN,
            truncation=True,
        ).to(device)

        # Generate n_samples per prompt in one call
        outs = model.generate(
            **enc,
            max_new_tokens=max_new_tokens,
            do_sample=True,
            temperature=temperature,
            num_return_sequences=n_samples,
            pad_token_id=tokenizer.pad_token_id,
        )
        # outs shape: (batch_size * n_samples, seq_len)
        # Output interleaving: [p0_s0, p0_s1, ..., p0_sN, p1_s0, ...]

        prompt_lens = enc["attention_mask"].sum(dim=1)  # actual token counts

        for bi in range(batch_size):
            prompt_len = prompt_lens[bi].item()
            for si in range(n_samples):
                out_idx = bi * n_samples + si
                response_ids = outs[out_idx][prompt_len:]
                response = tokenizer.decode(response_ids, skip_special_tokens=True)
                all_responses[start + bi].append(response)

    return all_responses


