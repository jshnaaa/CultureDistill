# CGM-GRPO: Guardian Advantage Augmentation
# ---------------------------------------------------------------------------

def apply_cgm_guardian_bonus(
    advantages: torch.Tensor,
    rewards: torch.Tensor,
    queries: list,
    countries: list,
    golds: list,
    r_outcomes: list,
    guardian_index: dict,
    guardian_lambda: float,
    w_culture_mode: str,
    rarity_map: dict,
    affinity_map: dict,
    n_samples: int,
    hit_threshold: float = 0.8,
) -> tuple:
    """
    Apply CGM-GRPO Guardian advantage augmentation in-place.

    Formula: bonus = lambda * w_culture * S_guardian
    Where:
        S_guardian = R_outcome_guardian * (R_guardian - R_on_bar_full)
        w_culture depends on mode (hit_only / hit_rarity / full)

    The bonus is UNIFORM for all on-policy rollouts of the same prompt
    (shifts the entire advantage distribution up/down).

    Returns:
        (modified_advantages, stats_dict)
    """
    n_prompts = advantages.size(0)
    stats = {
        "guardian_found": 0,
        "guardian_correct": 0,
        "n_applied": 0,
        "mean_w_culture": 0.0,
        "mean_s_guardian": 0.0,
    }

    for pi in range(n_prompts):
        country = countries[pi]
        query = queries[pi]
        gold = str(golds[pi]).strip()

        # Look up Guardian data
        key = (country.lower().strip(), query[:200].lower().strip())
        guardian_data = guardian_index.get(key, None)
        if guardian_data is None:
            continue
        stats["guardian_found"] += 1

        # Quality gate: Guardian must have answered correctly
        guardian_answer = guardian_data["guardian_answer"]
        if guardian_answer is None:
            continue
        r_outcome_guardian = 1.0 if guardian_answer == gold else 0.0
        if r_outcome_guardian < 0.5:
            continue
        stats["guardian_correct"] += 1

        # R_on_bar_full = mean of on-policy R_total for this prompt
        r_on_bar_full = rewards[pi].mean().item()

        # S_guardian = R_outcome_guardian * (R_guardian - R_on_bar_full)
        # R_guardian = 1.0 (since Guardian answered correctly)
        r_guardian = 1.0
        s_guardian = r_outcome_guardian * (r_guardian - r_on_bar_full)

        if abs(s_guardian) < 1e-8:
            continue

        # hit_rate for this prompt (fraction of on-policy correct)
        hit_rate = 0.0
        for si in range(n_samples):
            idx = pi * n_samples + si
            if idx < len(r_outcomes) and r_outcomes[idx] > 0.5:
                hit_rate += 1.0
        hit_rate /= n_samples

        # Compute w_culture based on mode
        country_key = country.lower().strip()
        if w_culture_mode == "hit_only":
            w_val = 1.0 - hit_rate
        elif w_culture_mode == "hit_rarity":
            rarity = rarity_map.get(country_key, 0.5)
            w_val = 0.67 * (1.0 - hit_rate) + 0.33 * rarity
        else:  # "full"
            rarity = rarity_map.get(country_key, 0.5)
            isolation = affinity_map.get(country_key, 0.5)
            w_val = 0.6 * (1.0 - hit_rate) + 0.3 * rarity + 0.1 * isolation

        w_val = max(0.0, min(1.0, w_val))

        # Necessity gate: if hit_rate >= threshold, skip guidance
        if hit_rate >= hit_threshold:
            w_val = 0.0

        # Apply uniform bonus to all samples of this prompt
        bonus = guardian_lambda * w_val * s_guardian
        advantages[pi] += bonus

        stats["mean_w_culture"] += w_val
        stats["mean_s_guardian"] += s_guardian
        stats["n_applied"] += 1

    # Normalize stats
    if stats["n_applied"] > 0:
        stats["mean_w_culture"] /= stats["n_applied"]
        stats["mean_s_guardian"] /= stats["n_applied"]

    return advantages, stats


