@torch.no_grad()
def validate(model, tokenizer, val_samples: list, device,
             max_samples: int = 200) -> float:
    """Compute validation accuracy (greedy decoding)."""
    model.eval()
    correct, total = 0, 0
    for obj in val_samples:
        if total >= max_samples:
            break
        prompt = build_prompt(obj["query"], obj.get("country", ""), tokenizer)
        enc = tokenizer(
            prompt, return_tensors="pt",
            max_length=MAX_PROMPT_LEN, truncation=True
        ).to(device)
        outs = model.generate(
            **enc, max_new_tokens=MAX_GEN_LEN,
            do_sample=False, temperature=None, top_p=None,
            pad_token_id=tokenizer.pad_token_id,
        )
        prompt_len = enc["input_ids"].shape[1]
        response = tokenizer.decode(outs[0][prompt_len:], skip_special_tokens=True)
        pred = extract_answer(response)
        if pred == str(obj["gt"]).strip():
            correct += 1
        total += 1
    model.train()
    return correct / total if total > 0 else 0.0


# ---------------------------------------------------------------------------
# Main training loop
# ---------------------------------------------------------------------------

def train(args):
    if not args.no_prm and args.prm_path is None:
        raise ValueError("--prm_path is required when PRM scoring is enabled. "
                         "Use --no_prm to skip PRM scoring.")

    policy_device = torch.device("cuda:0")
    prm_device = torch.device(
        "cuda:1" if torch.cuda.device_count() > 1 else "cuda:0")

    model_path = args.model_name

    # ---- Load Guardian index ----
    guardian_index = None
    if args.guardian_data:
        guardian_index = load_guardian_index(args.guardian_data)

    print(f"{'=' * 60}")
    print(f"CAMA-D CGM-GRPO: Culture-Guided Mixed-Policy GRPO")
    print(f"{'=' * 60}")
    print(f"Base model:    {model_path}")
    print(f"SFT adapter:   {args.sft_adapter or 'None (RL-only mode)'}")
    print(f"PRM path:      {args.prm_path}")
    print(f"Policy device: {policy_device}")
    print(f"PRM device:    {prm_device}")
    print(f"Alpha:         {args.alpha}")
    print(f"KL coef:       {KL_COEF}")
    print(f"LoRA rank:     {args.lora_r}")
    print(f"Guardian:      lambda={args.guardian_lambda}, "
          f"w_culture_mode={args.w_culture_mode}")
    print(f"Optimizations: Batch Generate (mini_batch={args.gen_mini_batch}), "
          f"Batch LogProb (ref={args.logprob_mini_batch}, "
          f"grad={args.logprob_mini_batch_grad})")

    # ---- Load data from pkl ----
    print(f"\nLoading data splits from: {args.data_pkl}")
    with open(args.data_pkl, "rb") as f:
        splits = pickle.load(f)
    train_data = splits["train"]
    val_data = splits["val"]

    # Apply --max_train_samples limit
    if args.max_train_samples > 0:
        train_data = train_data[:args.max_train_samples]
        print(f"  [SUBSET MODE] Using only {len(train_data)} training samples")

    print(f"  Data: train={len(train_data)}, val={len(val_data)}, "
          f"test={len(splits['test'])}")

    # ---- Compute culture maps (for w_culture) ----
    rarity_map, affinity_map = build_culture_maps(
        train_data, args.affinity_config
    )
    print(f"  Rarity map: {len(rarity_map)} country keywords")
    if affinity_map:
        print(f"  Affinity map: {len(affinity_map)} country keywords")

    # ---- Tokenizer ----
    tokenizer = AutoTokenizer.from_pretrained(model_path, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "left"  # Required for batch generation

    # ---- Build Policy model (cuda:0) ----
    print(f"\nLoading base model: {model_path}")
    base_model = AutoModelForCausalLM.from_pretrained(
        model_path, torch_dtype=torch.bfloat16, trust_remote_code=True
    )

    if args.sft_adapter:
        print(f"  Merging SFT LoRA adapter: {args.sft_adapter}")
        base_model = PeftModel.from_pretrained(base_model, args.sft_adapter)
        base_model = base_model.merge_and_unload()
        print(f"  SFT adapter merged into base model")

    # Apply new GRPO LoRA (this is what we train)
    lora_config = LoraConfig(
        task_type=TaskType.CAUSAL_LM,
        r=args.lora_r,
        lora_alpha=args.lora_alpha,
        lora_dropout=0.05,
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj",
                        "gate_proj", "up_proj", "down_proj"],
        bias="none",
    )
    policy = get_peft_model(base_model, lora_config).to(policy_device)
    policy.print_trainable_parameters()
    policy.enable_input_require_grads()
    policy.gradient_checkpointing_enable()

    # ---- PRM (frozen, on cuda:1) ----
    if not args.no_prm:
        prm_backbone = args.prm_backbone if args.prm_backbone else model_path
        print(f"\nLoading PRM on {prm_device}: {args.prm_path}")
        prm = CulturePRM_v3(
            prm_checkpoint_dir=args.prm_path,
            backbone_path=prm_backbone,
            sft_adapter_path=args.sft_adapter,
        ).to(prm_device)
        prm_tokenizer = AutoTokenizer.from_pretrained(
            prm_backbone, trust_remote_code=True
        )
        if prm_tokenizer.pad_token is None:
            prm_tokenizer.pad_token = prm_tokenizer.eos_token
        for p in prm.parameters():
            p.requires_grad_(False)
        prm.eval()
    else:
        prm = None
        prm_tokenizer = None
        print("  [PRM] Skipped (--no_prm mode)")

    # ---- Optimizer ----
    trainable_params = [p for p in policy.parameters() if p.requires_grad]
    optimizer = torch.optim.AdamW(
        trainable_params, lr=args.lr, weight_decay=0.0, betas=(0.9, 0.95)
    )

    # ---- Dataset & DataLoader ----
    grpo_ds = GRPOPromptDataset(train_data)
    loader = DataLoader(
        grpo_ds, batch_size=args.prompt_batch, shuffle=True, pin_memory=False
    )

    Path(args.output_dir).mkdir(parents=True, exist_ok=True)
    best_val_acc = 0.0
    no_improve = 0

    effective_batches = (
        len(loader) if args.batches_per_round < 0
        else min(args.batches_per_round, len(loader))
    )
    print(f"\n{'=' * 60}")
    print(f"GRPO prompts: {len(grpo_ds)} | "
          f"Rounds: {args.max_rounds} | n_samples: {args.n_samples}")
    print(f"Batches per round: {effective_batches} "
          f"(prompt_batch={args.prompt_batch})")
    print(f"Starting CGM-GRPO training...")
    print(f"{'=' * 60}")
    sys.stdout.flush()

    # ---- Training rounds ----
    for rnd in range(1, args.max_rounds + 1):
        round_loss = 0.0
        round_steps = 0
        round_r_outcome = 0.0
        round_r_total = 0.0
        round_w_culture = 0.0
        round_s_guardian = 0.0
        round_guardian_applied = 0
        round_n = 0

        for batch_idx, batch in enumerate(loader):
            if batch_idx >= effective_batches:
                break

            queries = batch["query"]
            countries = batch["country"]
            golds = batch["gt"]
            n_prompts = len(queries)

            if batch_idx % 5 == 0:
                print(f"  Round {rnd} | Batch {batch_idx+1}/{effective_batches} "
                      f"| {n_prompts}x{args.n_samples} samples", flush=True)

            # ===== Step 1: Build prompts =====
            prompts = [build_prompt(q, c, tokenizer)
                       for q, c in zip(queries, countries)]

            # ===== Step 2: BATCH GENERATE (Optimization 1) =====
            policy.eval()
            policy.gradient_checkpointing_disable()
            all_responses = batch_generate_responses(
                policy, tokenizer, prompts,
                n_samples=args.n_samples,
                max_new_tokens=MAX_GEN_LEN,
                temperature=args.temperature,
                device=policy_device,
                mini_batch_size=args.gen_mini_batch,
            )
            policy.gradient_checkpointing_enable()
            policy.train()
            torch.cuda.empty_cache()

            # ===== Step 3: Compute rewards =====
            rewards = torch.zeros(n_prompts, args.n_samples, device=policy_device)
            r_outcomes = []

            for pi, (responses_i, gold) in enumerate(zip(all_responses, golds)):
                for si, resp in enumerate(responses_i):
                    pred = extract_answer(resp)
                    r_outcomes.append(compute_r_outcome(pred, str(gold).strip()))

            # PRM scoring (on cuda:1, parallel with cuda:0 idle)
            if args.no_prm:
                r_processes = [0.0] * (n_prompts * args.n_samples)
            else:
                prm_inputs = []
                for pi in range(n_prompts):
                    for si in range(args.n_samples):
                        prm_inputs.append(build_prm_input(
                            countries[pi], queries[pi], all_responses[pi][si]
                        ))

                PRM_BATCH_SIZE = 20
                r_processes = []
                for i in range(0, len(prm_inputs), PRM_BATCH_SIZE):
                    batch_texts = prm_inputs[i:i + PRM_BATCH_SIZE]
                    batch_scores = prm.score_batch(
                        batch_texts, prm_tokenizer, prm_device, max_len=512
                    )
                    r_processes.extend(batch_scores)

            # Combine outcome + process rewards
            idx = 0
            for pi in range(n_prompts):
                for si in range(args.n_samples):
                    r_out = r_outcomes[idx]
                    r_proc = r_processes[idx]
                    if args.no_prm:
                        r_total = r_out
                    else:
                        r_total = args.alpha * r_out + (1 - args.alpha) * r_proc
                    rewards[pi, si] = r_total
                    round_r_outcome += r_out
                    round_r_total += r_total
                    round_n += 1
                    idx += 1

            # ===== Step 4: RLOO advantages (on-policy only) =====
            advantages = rloo_advantages(rewards)

            # ===== Step 5: CGM-GRPO Guardian bonus =====
            if guardian_index is not None:
                advantages, g_stats = apply_cgm_guardian_bonus(
                    advantages=advantages,
                    rewards=rewards,
                    queries=queries,
                    countries=countries,
                    golds=golds,
                    r_outcomes=r_outcomes,
                    guardian_index=guardian_index,
                    guardian_lambda=args.guardian_lambda,
                    w_culture_mode=args.w_culture_mode,
                    rarity_map=rarity_map,
                    affinity_map=affinity_map,
                    n_samples=args.n_samples,
                )
                round_w_culture += g_stats["mean_w_culture"]
                round_s_guardian += g_stats["mean_s_guardian"]
                round_guardian_applied += g_stats["n_applied"]

            # ===== Step 6: BATCH POLICY GRADIENT (Optimization 2) =====
            total_samples = n_prompts * args.n_samples

            # Flatten: keep only samples with non-zero advantage
            flat_prompts = []
            flat_responses = []
            flat_advantages = []
            for pi in range(n_prompts):
                for si in range(args.n_samples):
                    adv = advantages[pi, si].item()
                    if abs(adv) < 1e-8:
                        continue
                    flat_prompts.append(prompts[pi])
                    flat_responses.append(all_responses[pi][si])
                    flat_advantages.append(adv)

            if not flat_prompts:
                continue

            # Phase A: Batch reference log-probs (no gradient, adapter disabled)
            policy.eval()
            policy.gradient_checkpointing_disable()
            with policy.disable_adapter():
                ref_logprobs = batch_compute_logprobs(
                    policy, tokenizer, flat_prompts, flat_responses,
                    policy_device, require_grad=False,
                    mini_batch_size=args.logprob_mini_batch,
                )
            torch.cuda.empty_cache()

            # Phase B: Policy forward+backward with gradient accumulation
            policy.gradient_checkpointing_enable()
            policy.train()
            optimizer.zero_grad()
            accumulated_loss = 0.0
            loss_count = 0

            pb_batch = args.logprob_mini_batch_grad
            for mb_start in range(0, len(flat_prompts), pb_batch):
                mb_end = min(mb_start + pb_batch, len(flat_prompts))
                mb_prompts = flat_prompts[mb_start:mb_end]
                mb_responses = flat_responses[mb_start:mb_end]
                mb_advantages = flat_advantages[mb_start:mb_end]
                mb_ref_lps = ref_logprobs[mb_start:mb_end]

                # Batch forward for policy log-probs (with grad)
                policy_lps = batch_compute_logprobs(
                    policy, tokenizer, mb_prompts, mb_responses,
                    policy_device, require_grad=True,
                    mini_batch_size=pb_batch,
                )

                # Compute loss for this mini-batch
                mb_loss = torch.tensor(0.0, device=policy_device)
                for i in range(len(mb_prompts)):
                    lp_policy = policy_lps[i]
                    lp_ref = mb_ref_lps[i]
                    adv = mb_advantages[i]

                    if not isinstance(lp_policy, torch.Tensor):
                        continue
                    if not lp_policy.requires_grad:
                        continue

                    lp_ref_t = torch.tensor(lp_ref, device=policy_device)
                    kl = (lp_policy - lp_ref_t).clamp(min=-10, max=10)
                    # GRPO loss: maximize advantage-weighted log-prob, penalize KL
                    pg_loss = -(adv * lp_policy - KL_COEF * kl)
                    mb_loss = mb_loss + pg_loss

                # Normalize and backward
                if mb_loss.requires_grad:
                    mb_loss = mb_loss / max(total_samples, 1)
                    mb_loss.backward()
                    accumulated_loss += mb_loss.item()
                    loss_count += 1

            # Gradient step
            if loss_count > 0:
                torch.nn.utils.clip_grad_norm_(trainable_params, 1.0)
                optimizer.step()
                round_loss += accumulated_loss
                round_steps += 1

            # Periodic memory cleanup
            if batch_idx % 10 == 0:
                torch.cuda.empty_cache()

        # ===== Round summary =====
        avg_loss = round_loss / max(round_steps, 1)
        avg_r_outcome = round_r_outcome / max(round_n, 1)
        avg_r_total = round_r_total / max(round_n, 1)
        avg_w = round_w_culture / max(round_guardian_applied, 1)
        avg_s = round_s_guardian / max(round_guardian_applied, 1)

        print(f"\n  Round {rnd}/{args.max_rounds} summary: "
              f"loss={avg_loss:.4f} | "
              f"R_out={avg_r_outcome:.3f} | "
              f"R_tot={avg_r_total:.3f} | "
              f"w_cul={avg_w:.3f} | "
              f"S_g={avg_s:.3f} | "
              f"guardian_applied={round_guardian_applied}\n")

        # Validation every eval_every rounds
        if rnd % args.eval_every == 0:
            val_acc = validate(policy, tokenizer, val_data, policy_device)
            print(f"  [Eval] Round {rnd} | val_accuracy={val_acc:.4f}")

            if val_acc > best_val_acc:
                best_val_acc = val_acc
                no_improve = 0
                ckpt = Path(args.output_dir) / "best"
                policy.save_pretrained(str(ckpt))
                tokenizer.save_pretrained(str(ckpt))
                print(f"  Saved best (val_acc={best_val_acc:.4f}) -> {ckpt}")
            else:
                no_improve += 1
                print(f"  No improvement ({no_improve}/{args.patience})")
                if no_improve >= args.patience:
                    print("  Early stopping triggered.")
                    break

    # Save final model if no validation was run
    if best_val_acc == 0.0:
        ckpt = Path(args.output_dir) / "best"
        policy.save_pretrained(str(ckpt))
        tokenizer.save_pretrained(str(ckpt))
        print(f"  Saved final model -> {ckpt}")

    print(f"\nTraining complete. Best val_accuracy: {best_val_acc:.4f}")


