# Ablation: SFT-only (camad.md §2.1)
# ---------------------------------------------------------------------------

def train_sft_only(args):
    """
    Ablation §2.1 SFT-only: train DIRECTLY FROM THE BASE model with ONLY the
    supervised distillation term, no RL branch at all.

    To keep this a strictly controlled ablation (口径 A), the supervised signal
    is IDENTICAL to CAMAD's online SFT term:
        - target  = Judge final answer y_judge   (build_judge_sft_target)
        - loss    = L_SFT = mean(-log P(y_judge | x))   (compute_sft_loss)
        - weight  = w_sft = max(1 - hitrate, w_min)     (HitRateTracker)

    The only differences vs CAMAD are that there is NO GRPO advantage term and
    NO Guardian guidance, i.e. the objective is just  beta * w_sft * L_SFT
    (beta defaults to 1.0 for SFT-only so the supervised term is not scaled
    down; pass --beta to override if you want the exact CAMAD scaling).

    Because there is no RL, this runs on a SINGLE GPU (cuda:0) and needs NO
    PRM. The hitrate that drives w_sft is estimated from a lightweight greedy
    decode of the current policy (n=1 per prompt), so the difficulty-adaptive
    weighting follows the exact same formula/path as CAMAD.
    """
    policy_device = torch.device("cuda:0")

    model_path = MODEL_ALIASES.get(args.model_name, args.model_name)
    print(f"[SFT-only] Base model: {model_path}")

    # --- Tokenizer ---
    tokenizer = AutoTokenizer.from_pretrained(model_path, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "left"

    # --- Policy model: BASE + new trainable LoRA (supervised only) ---
    print("[SFT-only] Loading policy model (from BASE) ...")
    base = AutoModelForCausalLM.from_pretrained(
        model_path, torch_dtype=torch.bfloat16, trust_remote_code=True,
    )
    lora_cfg = LoraConfig(
        task_type=TaskType.CAUSAL_LM,
        r=args.lora_r, lora_alpha=args.lora_alpha,
        lora_dropout=0.05,
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj"],
    )
    policy = get_peft_model(base, lora_cfg)
    policy.to(policy_device)
    policy.train()
    if args.grad_checkpoint:
        policy.gradient_checkpointing_enable()
        policy.enable_input_require_grads()
    policy.print_trainable_parameters()

    # --- Data ---
    with open(args.data_pkl, "rb") as f:
        splits = pickle.load(f)
    train_samples = splits["train"]
    val_samples = splits.get("val", splits.get("test", []))
    train_samples = limit_train_samples(train_samples, args)
    print(f"[SFT-only] Train={len(train_samples)}  Val={len(val_samples)}")

    train_ds = GRPOPromptDataset(train_samples)
    loader = DataLoader(
        train_ds, batch_size=args.prompt_batch_size,
        shuffle=True, collate_fn=lambda b: b,
    )

    # --- HF-CAC index (Judge SFT target; Guardian unused in SFT-only) ---
    hf_cac_index = {}
    if args.guardian_data:
        hf_cac_index = load_hf_cac_index(args.guardian_data)
    else:
        print("[SFT-only] WARNING: --guardian_data not provided; no Judge "
              "targets will be available and nothing will be learned.")

    # --- Difficulty-adaptive weight tracker (same as CAMAD) ---
    tracker = HitRateTracker(
        w_min=args.w_min, momentum=args.ema_momentum, use_ema=args.use_ema,
    )

    optimizer = torch.optim.AdamW(
        [p for p in policy.parameters() if p.requires_grad], lr=args.lr,
    )

    os.makedirs(args.output_dir, exist_ok=True)
    best_acc = 0.0
    global_step = 0

    print(f"[SFT-only] Hyper-params: beta={args.beta} w_min={args.w_min} "
          f"ema={args.use_ema}(m={args.ema_momentum})")

    # Total batches actually run per round (for progress display).
    total_batches = min(
        args.batches_per_round,
        math.ceil(len(train_samples) / args.prompt_batch_size),
    )

    for rnd in range(args.max_rounds):
        print(f"\n========== Round {rnd + 1}/{args.max_rounds} ==========")
        round_batches = 0

        for batch in loader:
            if round_batches >= args.batches_per_round:
                break
            round_batches += 1
            global_step += 1

            prompts = [
                build_prompt(s["query"], s["country"], tokenizer) for s in batch
            ]
            golds = [s["gt"] for s in batch]
            countries = [s["country"] for s in batch]
            queries = [s["query"] for s in batch]
            n_prompts = len(batch)

            # Lightweight progress: the greedy decode + SFT backward below are
            # silent and can take a while, so surface where we are each batch.
            print(f"  [SFT-only] round {rnd + 1}/{args.max_rounds} "
                  f"batch {round_batches}/{total_batches} "
                  f"(step {global_step}) | greedy decode {n_prompts} prompts "
                  f"...", flush=True)

            # ---- Estimate hitrate via a lightweight greedy decode (n=1) ----
            # This keeps w_sft on the exact same formula/path as CAMAD without
            # needing RL rollouts or a PRM.
            policy.eval()
            greedy_resps = batch_generate_responses(
                policy, tokenizer, prompts, n_samples=1,
                max_new_tokens=MAX_GEN_LEN, temperature=1.0,
                device=policy_device, mini_batch_size=args.gen_mini_batch,
            )
            policy.train()

            # ---- Build Judge SFT targets + per-prompt w_sft ----
            sft_prompts = []
            sft_targets = []
            sft_weights = []
            for pi in range(n_prompts):
                pred = extract_answer(greedy_resps[pi][0])
                acc_cur = 1.0 if pred == golds[pi] else 0.0
                hr = tracker.update(countries[pi], queries[pi], acc_cur)
                _, w_sft = tracker.weights(hr)

                rec = lookup_hf_cac(hf_cac_index, countries[pi], queries[pi])
                judge_ans = rec["judge_answer"] if rec else None
                judge_text = rec["judge_text"] if rec else ""
                target = build_judge_sft_target(judge_ans, judge_text)
                if target is not None:
                    sft_prompts.append(prompts[pi])
                    sft_targets.append(target)
                    sft_weights.append(w_sft)

            # ---- Supervised backward: beta * w_sft * L_SFT ----
            optimizer.zero_grad()
            if sft_prompts:
                l_sft = compute_sft_loss(
                    policy, tokenizer, sft_prompts, sft_targets,
                    policy_device, mini_batch_size=args.sft_mini_batch,
                )
                w_sft_mean = sum(sft_weights) / len(sft_weights)
                loss = args.beta * w_sft_mean * l_sft
                loss.backward()
                torch.nn.utils.clip_grad_norm_(
                    [p for p in policy.parameters() if p.requires_grad], 1.0
                )
                optimizer.step()
            else:
                l_sft = torch.zeros((), device=policy_device)
                loss = torch.zeros((), device=policy_device)
                w_sft_mean = 0.0

            if global_step % args.log_every == 0:
                print(
                    f"  step {global_step} | loss {loss.item():.4f} "
                    f"(sft {l_sft.item():.4f}) | w_sft {w_sft_mean:.3f} | "
                    f"targets {len(sft_prompts)}/{n_prompts}"
                )

        # ---- Validation per round ----
        if val_samples:
            n_eval = min(args.max_eval, len(val_samples)) if args.max_eval > 0 \
                else len(val_samples)
            print(f"  [SFT-only] round {rnd + 1} validating on {n_eval} "
                  f"samples ...", flush=True)
            acc = validate(
                policy, tokenizer, val_samples, policy_device,
                max_eval=args.max_eval,
            )
            print(f"[SFT-only] Round {rnd + 1} val acc = {acc:.4f}")
            if acc > best_acc:
                best_acc = acc
                save_path = os.path.join(args.output_dir, "best")
                policy.save_pretrained(save_path)
                tokenizer.save_pretrained(save_path)
                print(f"[SFT-only] New best ({acc:.4f}) saved to {save_path}")

    final_path = os.path.join(args.output_dir, "final")
    policy.save_pretrained(final_path)
    tokenizer.save_pretrained(final_path)
    print(f"[SFT-only] Training done. Best val acc = {best_acc:.4f}. "
          f"Final adapter saved to {final_path}")


# ---------------------------------------------------------------------------
# Training (CAMAD joint SFT + RL)
# ---------------------------------------------------------------------------

def train(args):
    policy_device = torch.device("cuda:0")
    prm_device = torch.device("cuda:1")

    # RL-only ablation (camad.md §2.2): plain GRPO from base, i.e. NO Guardian
    # advantage guidance and NO online SFT term. The reward stays the same
    # (alpha*R_outcome + PRM process), the advantage degenerates to A_i=A_base.
    rl_only = (getattr(args, "mode", "camad") == "rl_only")
    tag = "RL-only" if rl_only else "CAMAD"

    model_path = MODEL_ALIASES.get(args.model_name, args.model_name)
    print(f"[{tag}] Base model: {model_path}")

    # --- Tokenizer ---
    tokenizer = AutoTokenizer.from_pretrained(model_path, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "left"  # left padding for generation

    # --- Policy model: BASE + new trainable LoRA ---
    # Both CAMAD and RL-only train directly from the base model. CAMAD injects
    # the supervised (SFT) signal ONLINE via the joint loss
    # L = L_GRPO + beta * w_sft * L_SFT, which is what distinguishes CAMAD's
    # "mixed" strategy from classic RLHF (base -> SFT -> RL) and avoids the
    # catastrophic forgetting of the staged pipeline. RL-only drops the SFT
    # term and the Guardian guidance, leaving plain GRPO.
    init_adapter = getattr(args, "init_adapter", None)
    if init_adapter:
        # SFT->RL stage 2 (camad.md §2.3): the RL stage starts FROM the SFT
        # checkpoint. We merge the SFT LoRA into the base weights so that (a)
        # the new trainable LoRA is initialized on top of the SFT-converged
        # model, and (b) the reference policy used by KL (policy.disable_adapter)
        # points at the SFT model -- i.e. RL is anchored on the SFT checkpoint,
        # exactly the classic RLHF semantics. This is ONLY a stage-2 starting
        # point; CAMAD / RL-only leave it None and start from the plain base.
        print(f"[{tag}] Loading policy model (from SFT checkpoint: "
              f"{init_adapter}) ...")
        base = AutoModelForCausalLM.from_pretrained(
            model_path, torch_dtype=torch.bfloat16, trust_remote_code=True,
        )
        base = PeftModel.from_pretrained(base, init_adapter)
        base = base.merge_and_unload()
    else:
        print(f"[{tag}] Loading policy model (from BASE, no SFT warm-up) ...")
        base = AutoModelForCausalLM.from_pretrained(
            model_path, torch_dtype=torch.bfloat16, trust_remote_code=True,
        )

    lora_cfg = LoraConfig(
        task_type=TaskType.CAUSAL_LM,
        r=args.lora_r, lora_alpha=args.lora_alpha,
        lora_dropout=0.05,
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj"],
    )
    policy = get_peft_model(base, lora_cfg)
    policy.to(policy_device)
    policy.train()
    if args.grad_checkpoint:
        policy.gradient_checkpointing_enable()
        policy.enable_input_require_grads()
    policy.print_trainable_parameters()

    # --- PRM (frozen, cuda:1) ---
    # The PRM is an independently trained scorer. --prm_sft_adapter only needs
    # to be set if the PRM was trained on a base that had an SFT adapter merged
    # in; for the CAMAD-from-base setup the PRM should likewise be trained on
    # the plain base model, so this is None by default.
    print(f"[{tag}] Loading PRM ...")
    prm = CulturePRM_v3(
        prm_checkpoint_dir=args.prm_path,
        backbone_path=model_path,
        sft_adapter_path=args.prm_sft_adapter,
    )
    prm.to(prm_device)
    prm.eval()

    # --- Data ---
    with open(args.data_pkl, "rb") as f:
        splits = pickle.load(f)
    train_samples = splits["train"]
    val_samples = splits.get("val", splits.get("test", []))
    train_samples = limit_train_samples(train_samples, args)
    print(f"[{tag}] Train={len(train_samples)}  Val={len(val_samples)}")

    train_ds = GRPOPromptDataset(train_samples)
    loader = DataLoader(
        train_ds, batch_size=args.prompt_batch_size,
        shuffle=True, collate_fn=lambda b: b,
    )

    # --- HF-CAC index (Guardian signal + Judge SFT target) ---
    hf_cac_index = {}
    if args.guardian_data:
        hf_cac_index = load_hf_cac_index(args.guardian_data)

    # --- Difficulty-adaptive weight tracker ---
    tracker = HitRateTracker(
        w_min=args.w_min, momentum=args.ema_momentum, use_ema=args.use_ema,
    )

    # --- Optimizer ---
    optimizer = torch.optim.AdamW(
        [p for p in policy.parameters() if p.requires_grad], lr=args.lr,
    )

    os.makedirs(args.output_dir, exist_ok=True)
    best_acc = 0.0
    global_step = 0

    print(f"[{tag}] Hyper-params: beta={args.beta} lambda_g={args.lambda_g} "
          f"w_min={args.w_min} ema={args.use_ema}(m={args.ema_momentum}) "
          f"alpha={args.alpha} n_samples={args.n_samples}"
          + (" | plain GRPO (no Guardian, no SFT)" if rl_only else ""))

    # Total batches actually run per round (for progress display).
    total_batches = min(
        args.batches_per_round,
        math.ceil(len(train_samples) / args.prompt_batch_size),
    )

    for rnd in range(args.max_rounds):
        print(f"\n========== Round {rnd + 1}/{args.max_rounds} ==========")
        round_batches = 0

        for batch in loader:
            if round_batches >= args.batches_per_round:
                break
            round_batches += 1
            global_step += 1

            # ---- Step 1: build prompts ----
            prompts = [
                build_prompt(s["query"], s["country"], tokenizer) for s in batch
            ]
            golds = [s["gt"] for s in batch]
            countries = [s["country"] for s in batch]
            queries = [s["query"] for s in batch]
            n_prompts = len(batch)

            # Lightweight progress: the generate/PRM/backward below are silent
            # and can take a while, so surface where we are each batch.
            print(f"  [{tag}] round {rnd + 1}/{args.max_rounds} "
                  f"batch {round_batches}/{total_batches} "
                  f"(step {global_step}) | generating {n_prompts}x"
                  f"{args.n_samples} rollouts ...", flush=True)

            # ---- Step 2: batch generate n_samples rollouts each ----
            policy.eval()
            all_responses = batch_generate_responses(
                policy, tokenizer, prompts, args.n_samples,
                MAX_GEN_LEN, args.temperature, policy_device,
                mini_batch_size=args.gen_mini_batch,
            )
            policy.train()

            # ---- Step 3: rewards (outcome + PRM process) ----
            rewards = torch.zeros(n_prompts, args.n_samples, device=policy_device)
            preds = [[None] * args.n_samples for _ in range(n_prompts)]

            # Outcome reward + parse predictions.
            for pi in range(n_prompts):
                for si in range(args.n_samples):
                    resp = all_responses[pi][si]
                    pred = extract_answer(resp)
                    preds[pi][si] = pred
                    rewards[pi, si] += compute_r_outcome(pred, golds[pi])

            # PRM process reward (batched on cuda:1).
            prm_inputs = []
            prm_map = []
            for pi in range(n_prompts):
                for si in range(args.n_samples):
                    txt = build_prm_input(
                        countries[pi], queries[pi], all_responses[pi][si]
                    )
                    prm_inputs.append(txt)
                    prm_map.append((pi, si))
            prm_scores = prm.score_batch(
                prm_inputs, tokenizer, prm_device, max_len=MAX_PROMPT_LEN
            )
            for (pi, si), sc in zip(prm_map, prm_scores):
                rewards[pi, si] += args.alpha * sc

            # ---- Step 4: GRPO base advantages ----
            adv = grpo_advantages(rewards)  # (n_prompts, n_samples)

            # ---- Step 5: per-prompt hitrate + per-rollout Guardian signal ----
            # w / w_sft per prompt (shared across its rollouts).
            w_per_prompt = []
            w_sft_per_prompt = []
            judge_targets = []  # SFT target per prompt (Judge final answer)
            for pi in range(n_prompts):
                acc_cur = sum(
                    1 for si in range(args.n_samples)
                    if preds[pi][si] == golds[pi]
                ) / args.n_samples
                hr = tracker.update(countries[pi], queries[pi], acc_cur)
                w, w_sft = tracker.weights(hr)
                w_per_prompt.append(w)
                w_sft_per_prompt.append(w_sft)

                rec = lookup_hf_cac(hf_cac_index, countries[pi], queries[pi])
                guardian_ans = rec["guardian_answer"] if rec else None
                judge_ans = rec["judge_answer"] if rec else None
                judge_text = rec["judge_text"] if rec else ""
                judge_targets.append(
                    build_judge_sft_target(judge_ans, judge_text)
                )

                # A_i = A_base + lambda_g * w * S_guardian  (per-rollout).
                # RL-only: skip Guardian guidance -> advantage stays A_base.
                if not rl_only:
                    for si in range(args.n_samples):
                        s_guard = guardian_cultural_match(
                            preds[pi][si], guardian_ans
                        )
                        adv[pi, si] = adv[pi, si] + args.lambda_g * w * s_guard

            # ---- Step 6: joint backward  L = L_GRPO + beta * w_sft * L_SFT ----
            # Flatten rollouts for GRPO log-probs.
            flat_prompts = []
            flat_resps = []
            flat_adv = []
            for pi in range(n_prompts):
                for si in range(args.n_samples):
                    flat_prompts.append(prompts[pi])
                    flat_resps.append(all_responses[pi][si])
                    flat_adv.append(adv[pi, si].item())
            flat_adv_t = torch.tensor(flat_adv, device=policy_device)

            # Reference log-probs (adapter disabled -> base policy).
            with policy.disable_adapter():
                lp_ref = batch_compute_logprobs(
                    policy, tokenizer, flat_prompts, flat_resps,
                    policy_device, require_grad=False,
                    mini_batch_size=args.logprob_mini_batch,
                )

            optimizer.zero_grad()

            # Policy log-probs WITH grad -> GRPO loss.
            lp_policy = batch_compute_logprobs(
                policy, tokenizer, flat_prompts, flat_resps,
                policy_device, require_grad=True,
                mini_batch_size=args.logprob_mini_batch,
            )
            kl = (lp_policy - lp_ref).clamp(min=-10, max=10)
            pg_loss = -(flat_adv_t * lp_policy - KL_COEF * kl)
            l_grpo = pg_loss.mean()

            # Judge SFT loss (weighted per prompt by w_sft).
            # RL-only: no online SFT term at all -> skip building it entirely
            # (avoids a wasted forward pass even if --guardian_data is given).
            sft_prompts = []
            sft_targets = []
            sft_weights = []
            if not rl_only:
                for pi in range(n_prompts):
                    if judge_targets[pi] is not None:
                        sft_prompts.append(prompts[pi])
                        sft_targets.append(judge_targets[pi])
                        sft_weights.append(w_sft_per_prompt[pi])

            if sft_prompts:
                # Weighted SFT: the loss is token-normalized, so we scale it by
                # the mean w_sft over the prompts that contributed a target.
                l_sft = compute_sft_loss(
                    policy, tokenizer, sft_prompts, sft_targets,
                    policy_device, mini_batch_size=args.sft_mini_batch,
                )
                w_sft_mean = sum(sft_weights) / len(sft_weights)
                l_sft_weighted = w_sft_mean * l_sft
            else:
                l_sft = torch.zeros((), device=policy_device)
                l_sft_weighted = torch.zeros((), device=policy_device)

            loss = l_grpo + args.beta * l_sft_weighted
            loss.backward()
            torch.nn.utils.clip_grad_norm_(
                [p for p in policy.parameters() if p.requires_grad], 1.0
            )
            optimizer.step()

            if global_step % args.log_every == 0:
                mean_w = sum(w_per_prompt) / len(w_per_prompt)
                mean_w_sft = sum(w_sft_per_prompt) / len(w_sft_per_prompt)
                mean_r = rewards.mean().item()
                print(
                    f"  step {global_step} | loss {loss.item():.4f} "
                    f"(grpo {l_grpo.item():.4f}, sft {l_sft.item():.4f}) | "
                    f"meanR {mean_r:.3f} | w {mean_w:.3f} w_sft {mean_w_sft:.3f}"
                )

        # ---- Validation per round ----
        if val_samples:
            n_eval = min(args.max_eval, len(val_samples)) if args.max_eval > 0 \
                else len(val_samples)
            print(f"  [{tag}] round {rnd + 1} validating on {n_eval} "
                  f"samples ...", flush=True)
            acc = validate(
                policy, tokenizer, val_samples, policy_device,
                max_eval=args.max_eval,
            )
            print(f"[{tag}] Round {rnd + 1} val acc = {acc:.4f}")
            if acc > best_acc:
                best_acc = acc
                save_path = os.path.join(args.output_dir, "best")
                policy.save_pretrained(save_path)
                tokenizer.save_pretrained(save_path)
                print(f"[{tag}] New best ({acc:.4f}) saved to {save_path}")

    # Final save.
    final_path = os.path.join(args.output_dir, "final")
    policy.save_pretrained(final_path)
    tokenizer.save_pretrained(final_path)
    print(f"[{tag}] Training done. Best val acc = {best_acc:.4f}. "
          f"Final adapter saved to {final_path}")


