# Optimized Batch Log-Prob Computation (Optimization 2)
# ---------------------------------------------------------------------------

def batch_compute_logprobs(
    model, tokenizer, prompts: list, responses: list,
    device, require_grad: bool = False, mini_batch_size: int = 8,
) -> list:
    """
    Compute mean log-prob of response tokens for multiple (prompt, response) pairs
    in batched forward passes.

    Instead of N serial forward passes, we batch them into groups of
    mini_batch_size for much higher throughput.

    Memory-efficient: computes log-prob via (target_logit - logsumexp) to avoid
    materializing full (batch, seq_len, vocab_size) softmax output.

    Args:
        prompts: List of prompt strings.
        responses: List of response strings (same length as prompts).
        require_grad: Whether to keep computation graph (True for Phase B).
        mini_batch_size: Sequences per forward pass.
            Phase A (no grad): use 8-10.
            Phase B (with grad): use 4 to limit activation memory.

    Returns:
        List of mean log-prob values (torch.Tensor if require_grad, else float).
    """
    assert len(prompts) == len(responses)
    n = len(prompts)
    results = [None] * n

    for start in range(0, n, mini_batch_size):
        end = min(start + mini_batch_size, n)
        batch_texts = [prompts[i] + responses[i] for i in range(start, end)]
        batch_prompts_slice = [prompts[i] for i in range(start, end)]

        # Tokenize full texts (prompt + response)
        enc_full = tokenizer(
            batch_texts,
            return_tensors="pt",
            padding=True,
            max_length=MAX_PROMPT_LEN + MAX_GEN_LEN,
            truncation=True,
        ).to(device)

        # Get prompt lengths to know where response starts
        prompt_lengths = []
        for p in batch_prompts_slice:
            p_enc = tokenizer(p, max_length=MAX_PROMPT_LEN, truncation=True)
            prompt_lengths.append(len(p_enc["input_ids"]))

        # Forward pass with appropriate gradient context
        ctx = torch.enable_grad() if require_grad else torch.no_grad()
        with ctx:
            outputs = model(
                input_ids=enc_full["input_ids"],
                attention_mask=enc_full["attention_mask"],
            )
            logits = outputs.logits  # (batch, seq_len, vocab)

            # Compute per-token log-probs for response portion only
            for bi in range(end - start):
                idx = start + bi
                p_len = prompt_lengths[bi]
                seq_len_i = int(enc_full["attention_mask"][bi].sum().item())

                if p_len >= seq_len_i:
                    # No response tokens
                    if require_grad:
                        results[idx] = torch.tensor(
                            0.0, device=device, requires_grad=True)
                    else:
                        results[idx] = 0.0
                    continue

                # Response logits: predict token[p_len:seq_len] from position[p_len-1:seq_len-1]
                resp_logits = logits[bi, p_len - 1:seq_len_i - 1, :]  # (resp_len, vocab)
                resp_targets = enc_full["input_ids"][bi, p_len:seq_len_i]  # (resp_len,)

                # Memory-efficient log-prob: gather + logsumexp
                # Instead of full log_softmax (materializes vocab-sized tensor)
                target_logits = resp_logits.gather(
                    1, resp_targets.unsqueeze(1)
                ).squeeze(1)  # (resp_len,)
                logsumexp_vals = resp_logits.float().logsumexp(dim=-1)  # (resp_len,)
                token_logprobs = target_logits.float() - logsumexp_vals  # (resp_len,)

                mean_lp = token_logprobs.mean()

                if require_grad:
                    results[idx] = mean_lp
                else:
                    results[idx] = mean_lp.item()

    return results


