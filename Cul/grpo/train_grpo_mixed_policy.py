@torch.no_grad()
def validate(model, tokenizer, val_samples: list, device,
             max_eval: int = 100) -> float:
    """Greedy-decode accuracy on a validation subset."""
    model.eval()
    correct = 0
    total = 0
    subset = val_samples[:max_eval]

    for obj in subset:
        prompt = build_prompt(obj["query"], obj.get("country", ""), tokenizer)
        enc = tokenizer(
            prompt, return_tensors="pt",
            max_length=MAX_PROMPT_LEN, truncation=True,
        ).to(device)
        out = model.generate(
            **enc, max_new_tokens=MAX_GEN_LEN, do_sample=False,
            pad_token_id=tokenizer.pad_token_id,
        )
        response = tokenizer.decode(
            out[0][enc["input_ids"].shape[1]:], skip_special_tokens=True
        )
        pred = extract_answer(response)
        if pred == str(obj["gt"]).strip():
            correct += 1
        total += 1

    model.train()
    return correct / max(1, total)


