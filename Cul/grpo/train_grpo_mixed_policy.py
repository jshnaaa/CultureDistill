def main():
    parser = argparse.ArgumentParser(
        description="CAMA-D CGM-GRPO: Culture-Guided Mixed-Policy GRPO"
    )

    # Model & data
    parser.add_argument("--model_name", type=str, required=True,
                        help="'llama', 'qwen', or full HuggingFace model path")
    parser.add_argument("--sft_adapter", type=str, default=None,
                        help="Stage 1 SFT LoRA adapter path (for SFT+RL mode)")
    parser.add_argument("--data_pkl", type=str, required=True,
                        help="Path to splits pkl (from split_data.py)")
    parser.add_argument("--prm_path", type=str, default=None,
                        help="PRM checkpoint directory")
    parser.add_argument("--prm_backbone", type=str, default=None,
                        help="PRM backbone path (defaults to base model)")
    parser.add_argument("--output_dir", type=str, required=True,
                        help="Directory to save checkpoints")

    # Training hyperparams
    parser.add_argument("--alpha", type=float, default=DEFAULT_ALPHA,
                        help="R_outcome weight in R_total (default: 0.6)")
    parser.add_argument("--n_samples", type=int, default=5,
                        help="Rollout samples per prompt (default: 5)")
    parser.add_argument("--temperature", type=float, default=0.7,
                        help="Generation temperature (default: 0.7)")
    parser.add_argument("--max_rounds", type=int, default=20,
                        help="Max training rounds (default: 20)")
    parser.add_argument("--eval_every", type=int, default=5,
                        help="Validation every N rounds (default: 5)")
    parser.add_argument("--patience", type=int, default=3,
                        help="Early stop patience (default: 3)")
    parser.add_argument("--prompt_batch", type=int, default=8,
                        help="Prompts per GRPO batch (default: 8)")
    parser.add_argument("--lr", type=float, default=5e-5,
                        help="Learning rate (default: 5e-5)")
    parser.add_argument("--lora_r", type=int, default=16,
                        help="LoRA rank (default: 16)")
    parser.add_argument("--lora_alpha", type=int, default=32,
                        help="LoRA alpha (default: 32)")
    parser.add_argument("--batches_per_round", type=int, default=130,
                        help="Max batches per round (-1 = all, default: 130)")
    parser.add_argument("--no_prm", action="store_true",
                        help="Disable PRM scoring (R_total = R_outcome only)")

    # Sample limit
    parser.add_argument("--max_train_samples", type=int, default=0,
                        help="Max training samples. 0=all, N=first N samples.")

    # CGM-GRPO specific
    parser.add_argument("--guardian_data", type=str, default=None,
                        help="HF-CAC inference JSONL with Guardian responses")
    parser.add_argument("--guardian_lambda", type=float, default=0.5,
                        help="Guardian guidance strength (default: 0.5)")
    parser.add_argument("--w_culture_mode", type=str, default="hit_only",
                        choices=["hit_only", "hit_rarity", "full"],
                        help="w_culture computation mode (default: hit_only)")
    parser.add_argument("--affinity_config", type=str, default=None,
                        help="Path to hf_cac_config.yaml (for hit_rarity/full)")

    # Batch optimization params
    parser.add_argument("--gen_mini_batch", type=int, default=4,
                        help="Prompts per batch-generate call (default: 4). "
                             "Reduce to 2 if OOM during generation.")
    parser.add_argument("--logprob_mini_batch", type=int, default=8,
                        help="Samples per batch in Phase A ref log-prob "
                             "(no grad, default: 8).")
    parser.add_argument("--logprob_mini_batch_grad", type=int, default=4,
                        help="Samples per batch in Phase B policy log-prob "
                             "(with grad, default: 4). Reduce if OOM.")

    args = parser.parse_args()

    # Resolve model alias
    args.model_name = MODEL_ALIASES.get(args.model_name, args.model_name)

    train(args)


if __name__ == "__main__":
    main()
