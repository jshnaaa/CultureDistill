def load_affinity_matrix(config_path: str) -> tuple:
    """
    Load cultural affinity matrix and region keywords from hf_cac_config.yaml.

    Returns:
        (affinity_matrix: list[list[float]], country_to_circle: dict[str, int])
    """
    with open(config_path, "r") as f:
        config = yaml.safe_load(f)

    matrix = config["cultural_affinity_matrix"]
    country_to_circle = {}

    for idx, role in enumerate(config["culture_roles"]):
        for keyword in role.get("region_keywords", []):
            country_to_circle[keyword.lower().strip()] = idx

    return matrix, country_to_circle


def build_culture_maps(train_data: list, affinity_config: str = None) -> tuple:
    """
    Build rarity_map and affinity_map from training data.

    Returns:
        (rarity_map: dict[str, float], affinity_map: dict[str, float])
        Maps country_name_lower -> value.
    """
    rarity_map = {}
    affinity_map = {}

    if not affinity_config or not os.path.exists(affinity_config):
        return rarity_map, affinity_map

    matrix, country_to_circle = load_affinity_matrix(affinity_config)

    # Compute rarity per circle
    circle_counts = defaultdict(int)
    total = 0
    for sample in train_data:
        country = sample.get("country", "").lower().strip()
        circle_idx = country_to_circle.get(country, -1)
        if circle_idx >= 0:
            circle_counts[circle_idx] += 1
        total += 1

    circle_rarity = {}
    for idx in range(len(matrix)):
        freq = circle_counts[idx] / max(total, 1)
        circle_rarity[idx] = 1.0 - freq

    # Compute isolation (1 - avg_affinity) per circle
    circle_isolation = {}
    n = len(matrix)
    for i in range(n):
        off_diag = [matrix[i][j] for j in range(n) if j != i]
        avg_aff = sum(off_diag) / max(len(off_diag), 1)
        circle_isolation[i] = 1.0 - avg_aff

    # Build per-country maps
    for country_name, circle_idx in country_to_circle.items():
        rarity_map[country_name] = circle_rarity.get(circle_idx, 0.5)
        affinity_map[country_name] = circle_isolation.get(circle_idx, 0.5)

    return rarity_map, affinity_map


